class Report:
    def __init__(self):
        self.fails = 0
        self.warns = 0

    def fail(self, where, msg):
        print(f"FAIL {where}: {msg}")
        self.fails += 1

    def warn(self, where, msg):
        print(f"WARN {where}: {msg}")
        self.warns += 1


# --------------------------------------------------------------------------
# Minimal front-matter reader
# --------------------------------------------------------------------------
# Deliberately supports only the subset the schemas use:
#   key: scalar
#   key: []                 (also [a, b] for short lists of plain scalars)
#   key:
#     - scalar
#   key:
#     - subkey: scalar
#       subkey: scalar
# Anything else raises, loudly, rather than being silently misread.


def _strip_quotes(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def parse_front_matter(text: str):
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise ValueError("file does not start with a '---' front-matter fence")
    try:
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    except StopIteration:
        raise ValueError("front matter is not closed by a second '---'")

    data = {}
    inline = set()
    key = None
    for raw in lines[1:end]:
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue

        indent = len(raw) - len(raw.lstrip(" "))

        if indent == 0:
            if ":" not in stripped:
                raise ValueError(f"cannot parse front-matter line: {raw!r}")
            key, _, value = stripped.partition(":")
            key = key.strip()
            if key in data:
                raise ValueError(f"duplicate front-matter key {key!r}")
            value = value.strip()
            if value.startswith("[") and value.endswith("]"):
                inner = value[1:-1].strip()
                data[key] = [_strip_quotes(x) for x in inner.split(",") if x.strip()]
                inline.add(key)
            else:
                value = _strip_quotes(value)
                data[key] = value if value not in ("", "null", "~") else None
            continue

        if stripped.startswith("- "):
            if key is None:
                raise ValueError(f"list item before any key: {raw!r}")
            if key in inline:
                raise ValueError(f"key {key!r} has both an inline list and list items")
            item = stripped[2:].strip()
            if data.get(key) in (None, ""):
                data[key] = []
            if not isinstance(data[key], list):
                raise ValueError(f"key {key!r} has both a scalar and list items")
            if ":" in item:
                k, _, v = item.partition(":")
                data[key].append({k.strip(): _strip_quotes(v)})
            else:
                data[key].append(_strip_quotes(item))
            continue

        # continuation of the last mapping in the current list
        if key is None or not isinstance(data.get(key), list) or not data[key]:
            raise ValueError(f"unexpected indented line: {raw!r}")
        last = data[key][-1]
        if not isinstance(last, dict):
            raise ValueError(f"cannot add a field to a scalar list item: {raw!r}")
        if ":" not in stripped:
            raise ValueError(f"cannot parse front-matter line: {raw!r}")
        k, _, v = stripped.partition(":")
        k = k.strip()
        if k in last:
            raise ValueError(f"duplicate field {k!r} in a list item of {key!r}: {raw!r}")
        last[k] = _strip_quotes(v)

    return data, end


def load_md(path: Path):
    text = path.read_text(encoding="utf-8")
    meta, end = parse_front_matter(text)
    body = "\n".join(text.splitlines()[end + 1 :])
    return meta, body



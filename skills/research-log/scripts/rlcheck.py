def _parse_opts(args, spec):
    """Tiny option parser: spec maps '--name' to True if it takes a value."""
    opts = {}
    i = 0
    while i < len(args):
        a = args[i]
        if a not in spec:
            raise ValueError(f"unknown option {a!r}")
        if spec[a]:
            if i + 1 >= len(args):
                raise ValueError(f"option {a} needs a value")
            opts[a] = args[i + 1]
            i += 2
        else:
            opts[a] = True
            i += 1
    return opts



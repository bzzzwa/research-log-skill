def _hash_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def digest(root: Path, rel: str) -> str:
    """Digest of a file or of a directory tree, as 'sha256:...' or 'tree:...'."""
    target = (root / rel).resolve()
    if not target.exists():
        return "missing"
    if target.is_file():
        return "sha256:" + _hash_file(target)

    entries = []
    for path in sorted(target.rglob("*")):
        if any(part in SKIP_NAMES for part in path.parts):
            continue
        if path.is_file():
            entries.append(
                path.relative_to(target).as_posix() + "\0" + _hash_file(path)
            )
    h = hashlib.sha256("\n".join(entries).encode("utf-8"))
    return "tree:" + h.hexdigest()


def _norm(rel: str) -> str:
    return rel.replace("\\", "/").strip().strip("/")


def covered_by(path: str, inputs) -> bool:
    """True if path is one of the inputs or lies inside an input directory."""
    p = _norm(path)
    for item in inputs:
        q = _norm(item)
        if p == q or p.startswith(q + "/"):
            return True
    return False



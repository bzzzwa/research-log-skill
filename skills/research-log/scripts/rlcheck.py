def _version_of(path: Path):
    """The __version__ declared in a copy of rlcheck.py, or None."""
    try:
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith("__version__"):
                return line.split("=", 1)[1].strip().strip("\"'")
    except OSError:
        pass
    return None


